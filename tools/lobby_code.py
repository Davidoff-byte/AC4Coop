#!/usr/bin/env python3
"""lobby_code.py - lobby codes: an IPv4 address + UDP port as 12 Crockford-base32 characters (XXXX-XXXX-XXXX).

Spec: docs/LEDGER.md slice 2 and docs/design/lobby-code.md.
  bytes : a, b, c, d (the IPv4 address in dotted order), then the port big-endian (2 bytes)
  check : CRC-16/CCITT-FALSE of those 6 bytes (poly 0x1021, init 0xFFFF, no reflection, no final xor), low 12 bits
  value : (48-bit big-endian bytes << 12) | check  = 60 bits
  text  : 12 symbols x 5 bits, most significant first, alphabet 0123456789ABCDEFGHJKMNPQRSTVWXYZ, shown XXXX-XXXX-XXXX
  decode: either case; '-' and spaces ignored; O->0, I/L->1; exactly 12 symbols and a matching check, else invalid

Usage:
  py tools\\lobby_code.py encode 1.2.3.4 47801
  py tools\\lobby_code.py decode XXXX-XXXX-XXXX
  py tools\\lobby_code.py --selftest          # vectors + negative controls + typo sweep + header drift check
  py tools\\lobby_code.py --gen-header        # (re)write src/lobby_code_vectors.h from tools/testdata/lobby_codes.txt
Exit 0 = ok, 1 = selftest failed / invalid code, 2 = usage.
"""
from __future__ import annotations

import random
import sys
from pathlib import Path

ALPHABET = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"
ROOT = Path(__file__).resolve().parents[1]
VECTORS = ROOT / "tools" / "testdata" / "lobby_codes.txt"
HEADER = ROOT / "src" / "lobby_code_vectors.h"


def crc16_ccitt_false(data: bytes) -> int:
    crc = 0xFFFF
    for b in data:
        crc ^= b << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) & 0xFFFF if crc & 0x8000 else (crc << 1) & 0xFFFF
    return crc


def _ip_bytes(ip: str) -> bytes:
    parts = ip.split(".")
    if len(parts) != 4:
        raise ValueError(f"not an IPv4 address: {ip!r}")
    vals = [int(p) for p in parts]
    if any(not 0 <= v <= 255 for v in vals):
        raise ValueError(f"not an IPv4 address: {ip!r}")
    return bytes(vals)


def encode(ip: str, port: int) -> str:
    if not 0 <= port <= 0xFFFF:
        raise ValueError(f"port out of range: {port}")
    raw = _ip_bytes(ip) + port.to_bytes(2, "big")
    value = (int.from_bytes(raw, "big") << 12) | (crc16_ccitt_false(raw) & 0x0FFF)
    sym = "".join(ALPHABET[(value >> (5 * (11 - i))) & 0x1F] for i in range(12))
    return f"{sym[0:4]}-{sym[4:8]}-{sym[8:12]}"


def decode(text: str) -> tuple[str, int] | None:
    s = []
    for ch in text:
        if ch in "- ":
            continue
        c = ch.upper()
        c = {"O": "0", "I": "1", "L": "1"}.get(c, c)
        k = ALPHABET.find(c)
        if k < 0:
            return None
        s.append(k)
    if len(s) != 12:
        return None
    value = 0
    for k in s:
        value = (value << 5) | k
    raw = (value >> 12).to_bytes(6, "big")
    if crc16_ccitt_false(raw) & 0x0FFF != value & 0x0FFF:
        return None
    return ".".join(str(b) for b in raw[:4]), int.from_bytes(raw[4:6], "big")


def load_vectors(path: Path = VECTORS):
    valid, accept, reject = [], [], []
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line or line.startswith("#"):
            continue
        f = line.split("\t")
        if f[0] == "valid":
            valid.append((f[1], f[2]))
        elif f[0] == "accept":
            accept.append((f[1], f[2]))
        elif f[0] == "reject":
            reject.append(f[1] if len(f) > 1 else "")
        else:
            raise ValueError(f"{path.name}:{n}: unknown record {f[0]!r}")
    return valid, accept, reject


def _split(addr: str) -> tuple[str, int]:
    ip, port = addr.rsplit(":", 1)
    return ip, int(port)


def header_text() -> str:
    valid, accept, reject = load_vectors()
    esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
    lines = [
        "// GENERATED by tools/lobby_code.py --gen-header from tools/testdata/lobby_codes.txt - do not edit.",
        "// tools/lobby_code.py --selftest fails if this file and the vector file disagree.",
        "#pragma once",
        "#include <cstdint>",
        "namespace LobbyCodeVectors {",
        "struct Valid { const char* ip; uint16_t port; const char* code; };",
        "struct Accept { const char* ip; uint16_t port; const char* text; };",
        "static const Valid kValid[] = {",
    ]
    lines += [f'    {{ "{ip}", {port}, "{esc(code)}" }},' for ip, port, code in ((*_split(a), c) for a, c in valid)]
    lines += ["};", "static const Accept kAccept[] = {"]
    lines += [f'    {{ "{ip}", {port}, "{esc(t)}" }},' for ip, port, t in ((*_split(a), t) for a, t in accept)]
    lines += ["};", "static const char* const kReject[] = {"]
    lines += [f'    "{esc(t)}",' for t in reject]
    lines += ["};", "}  // namespace LobbyCodeVectors", ""]
    return "\n".join(lines)


def selftest() -> int:
    fails = []
    if crc16_ccitt_false(b"123456789") != 0x29B1:
        fails.append("crc check value")
    valid, accept, reject = load_vectors()
    for addr, code in valid:
        ip, port = _split(addr)
        if encode(ip, port) != code:
            fails.append(f"encode {addr} -> {encode(ip, port)} != {code}")
        if decode(code) != (ip, port):
            fails.append(f"decode {code} -> {decode(code)}")
    for addr, text in accept:
        if decode(text) != _split(addr):
            fails.append(f"accept {text!r} -> {decode(text)}")
    for text in reject:
        if decode(text) is not None:
            fails.append(f"reject {text!r} decoded to {decode(text)}")
    # Typo sweep (the ledger's measurement): every single-symbol substitution and adjacent swap must be rejected.
    rnd = random.Random(20261112)
    subs = swaps = bad = 0
    for _ in range(300):
        ip = ".".join(str(rnd.randrange(256)) for _ in range(4)); port = rnd.randrange(65536)
        sym = encode(ip, port).replace("-", "")
        for i in range(12):
            for c in ALPHABET:
                if c == sym[i]:
                    continue
                subs += 1
                if decode(sym[:i] + c + sym[i + 1:]) is not None:
                    bad += 1
            if i < 11 and sym[i] != sym[i + 1]:
                swaps += 1
                if decode(sym[:i] + sym[i + 1] + sym[i] + sym[i + 2:]) is not None:
                    bad += 1
    if bad:
        fails.append(f"typo sweep: {bad} of {subs + swaps} mistyped codes decoded")
    if not HEADER.exists() or HEADER.read_text(encoding="utf-8") != header_text():
        fails.append(f"{HEADER.relative_to(ROOT)} is missing or out of date (run --gen-header)")
    n = len(valid) + len(accept) + len(reject)
    if fails:
        print("[Lobby] code selftest: FAIL " + "; ".join(fails))
        return 1
    print(f"[Lobby] code selftest: PASS n={n} typo_sweep={subs} substitutions + {swaps} swaps rejected")
    return 0


def main(argv: list[str]) -> int:
    if argv[:1] == ["--selftest"]:
        return selftest()
    if argv[:1] == ["--gen-header"]:
        HEADER.write_text(header_text(), encoding="utf-8", newline="\r\n")
        print(f"wrote {HEADER.relative_to(ROOT)}")
        return 0
    if len(argv) == 3 and argv[0] == "encode":
        print(encode(argv[1], int(argv[2])))
        return 0
    if len(argv) == 2 and argv[0] == "decode":
        r = decode(argv[1])
        print("invalid" if r is None else f"{r[0]}:{r[1]}")
        return 0 if r else 1
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
