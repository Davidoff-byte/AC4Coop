#!/usr/bin/env python3
"""deploy_check.py - I-704: built ASI vs deployed ASI vs HEAD, one verdict.

Prints the sha256 of bin\\AC4Coop.asi and of <AC4_GAME_DIR>\\AC4Coop.asi, the HEAD commit, and the stamp each
ASI carries (the AC4Coop_BuildStamp literal from src/dllmain.cpp: "AC4COOP_BUILD commit=<short> tree=<clean|
dirty>", generated by tools/make_build_info.ps1). Read-only: it never copies or deploys anything.

  py tools\\deploy_check.py            exit 0 = built == deployed (sha256) and built stamp commit == HEAD,
                                      tree=clean; exit 1 on any mismatch or missing file
  py tools\\deploy_check.py --built-only    skip the deployed copy (no game folder needed)

An ASI built before the stamp literal existed reports stamp=none and fails.
"""
from __future__ import annotations

import argparse
import hashlib
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILT = os.path.join(ROOT, "bin", "AC4Coop.asi")
STAMP = re.compile(rb"AC4COOP_BUILD commit=([0-9A-Za-z]+) tree=([a-z]+)\x00")


def sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def stamp(path: str):
    with open(path, "rb") as f:
        hits = STAMP.findall(f.read())
    if len(hits) != 1:
        return None                     # absent, or ambiguous: both fail
    return hits[0][0].decode(), hits[0][1].decode()


def head() -> str:
    out = subprocess.run(["git", "-C", ROOT, "rev-parse", "HEAD"], capture_output=True, text=True)
    return out.stdout.strip() if out.returncode == 0 else ""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--built-only", action="store_true", help="do not compare with the deployed ASI")
    a = ap.parse_args()

    fails = []
    h = head()
    print(f"HEAD      {h or '(git failed)'}")
    if not h:
        fails.append("HEAD unknown")

    def report(label: str, path: str):
        if not os.path.isfile(path):
            print(f"{label:9} MISSING {path}")
            fails.append(f"{label} missing")
            return None, None
        d, s = sha256(path), stamp(path)
        st = f"commit={s[0]} tree={s[1]}" if s else "stamp=none"
        print(f"{label:9} sha256={d} {st}  {path}")
        return d, s

    bd, bs = report("built", BUILT)
    if bs:
        if not h or not h.startswith(bs[0].lower()) or len(bs[0]) < 4:
            fails.append(f"built stamp commit {bs[0]} != HEAD {h[:len(bs[0])]}")
        if bs[1] != "clean":
            fails.append(f"built tree={bs[1]}")
    elif bd:
        fails.append("built ASI has no (unique) AC4COOP_BUILD stamp")

    if not a.built_only:
        game = os.environ.get("AC4_GAME_DIR")
        if not game:
            try:
                sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
                import paths  # noqa: E402
                game = paths.GAME_DIR
            except SystemExit as e:
                print(e)
                game = None
        if not game:
            fails.append("AC4_GAME_DIR not set")
        else:
            dd, ds = report("deployed", os.path.join(game, "AC4Coop.asi"))
            if bd and dd and bd != dd:
                fails.append("deployed sha256 != built sha256")

    if fails:
        print("VERDICT: MISMATCH - " + "; ".join(fails))
        return 1
    print("VERDICT: MATCH")
    return 0


if __name__ == "__main__":
    sys.exit(main())
